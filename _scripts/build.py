"""Render the portfolio into plain HTML using Python's standard library."""

import argparse
import json
import re
from datetime import date
from html import escape
from pathlib import Path
from urllib.parse import urlsplit
from xml.etree.ElementTree import Element, SubElement, tostring

from content_strategy import render_content_strategy
from keyword_strategy import definition, render_keyword_strategy

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://mosambrook-ai.github.io/Portfolio-Content-Marketing/"
MARKER = "<!-- Generated by _scripts/build.py -->"
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def required(entry, fields):
    for field in fields:
        value = entry.get(field)
        if not isinstance(value, str) or not value.strip() or value.startswith("["):
            raise ValueError(f"{entry['id']}: enter a value for {field}")


def local_file(value, folder):
    path = Path(value)
    base = ROOT / folder
    full = (base / path).resolve()
    if path.is_absolute() or not full.is_relative_to(base) or not full.is_file():
        raise ValueError(f"Missing or invalid {folder} file: {value}")
    return full


def external_url(value):
    url = urlsplit(value)
    if url.scheme not in ("http", "https") or not url.hostname:
        raise ValueError(f"Expected a full HTTP(S) URL: {value}")
    return escape(value)


def image_html(image):
    required(dict(image, id="image"), ("src", "alt"))
    if not image["src"].startswith("assets/"):
        raise ValueError("Image paths must start with assets/")
    local_file(image["src"], ".")
    attrs = {key: image[key] for key in ("src", "alt", "width", "height", "sizes", "srcset") if key in image}
    for key in ("width", "height"):
        if not isinstance(attrs.get(key), int) or attrs[key] < 1:
            raise ValueError(f"Provide a positive {key} for {image['src']}")
    for variant in attrs.get("srcset", "").split(","):
        if variant:
            local_file(variant.strip().split()[0], ".")
    return "<img " + " ".join(f'{key}="{escape(str(value))}"' for key, value in attrs.items()) + ' decoding="async" loading="lazy">'


def published_entries(entries, kind):
    ids, slugs = set(), set()
    for entry in entries:
        required(entry, ("id", "slug", "status"))
        for value, seen in ((entry["id"], ids), (entry["slug"], slugs)):
            if not SLUG.fullmatch(value) or value in seen:
                raise ValueError(f"Invalid or repeated {kind} identifier: {value}")
            seen.add(value)
        if entry["status"] == "draft":
            continue
        if entry["status"] != "published":
            raise ValueError(f"{entry['id']}: use draft or published")
        required(entry, ("title", "category", "description"))
        required(dict(entry["seo"], id=entry["id"]), ("title", "description"))
        if kind == "work":
            required(entry, ("timeframe", "body"))
            if not entry.get("skills"):
                raise ValueError(f"{entry['id']}: add skills")
            image_html(entry["image"])
            for link in entry.get("external_links", []):
                required(dict(link, id=entry["id"]), ("label", "url"))
                external_url(link["url"])
        else:
            if entry.get("date"):
                date.fromisoformat(entry["date"])
            if entry.get("external_url"):
                external_url(entry["external_url"])
            if not entry.get("body") and not entry.get("external_url"):
                raise ValueError(f"{entry['id']}: provide an article body or external URL")
            if entry.get("image"):
                image_html(entry["image"])
        yield entry


def anchor(entry, kind):
    value = entry.get("legacy_hash", ("case-" if kind == "work" else "article-") + entry["slug"])
    if not SLUG.fullmatch(value):
        raise ValueError(f"Invalid legacy hash: {value}")
    return value


def route(entry, kind):
    return f"{kind}/{entry['slug']}/"


def target(entry, kind):
    return route(entry, kind) if entry.get("dedicated") else "#" + anchor(entry, kind)


def project_row(entry, number, home):
    attrs = "" if home else ' data-view-heading="2"'
    meta = escape(entry["category"] + ", " + entry["timeframe"])
    return (
        f'<a class="row" href="{target(entry, "work")}"><span class="no m">No. {number}</span>'
        f'<span class="tx"><h3 class="project-title"{attrs}>{escape(entry["title"])}</h3>'
        f'<span class="m">{meta}</span><span class="ln">{escape(entry["description"])}</span></span>'
        f'<span class="pw">{image_html(entry["image"])}</span></a>'
    )


def body(entry):
    return local_file(entry["body"], "_content").read_text(encoding="utf-8").strip()


def writing_feature(entry):
    meta = escape(entry["category"])
    if entry.get("publisher"):
        meta += " · Published by " + escape(entry["publisher"])
    if entry.get("date"):
        day = date.fromisoformat(entry["date"])
        meta += f' · <time datetime="{day}">{day.day} {day:%B %Y}</time>'
    quote = f'<blockquote><p>“{escape(entry["quotation"])}”</p></blockquote>\n' if entry.get("quotation") else ""
    photo = image_html(entry["image"]) + "\n" if entry.get("image") else ""
    if entry.get("dedicated"):
        link = f'<p><a href="{route(entry, "writing")}">Read the Essay</a></p>'
    elif entry.get("body"):
        link = body(entry)
    else:
        link = f'<p><a href="{external_url(entry["external_url"])}">Read the Essay</a></p>'
    identifier = "" if entry.get("dedicated") else f' id="{anchor(entry, "writing")}" tabindex="-1"'
    return (
        f'<article class="essay"{identifier}>\n<p class="m">{meta}</p>\n'
        f'<h3 class="essay-title" data-view-heading="2">{escape(entry["title"])}</h3>'
        f'<p class="lead">{escape(entry["description"])}</p>\n{photo}{quote}{link}\n</article>'
    )


def project_case(entry):
    content = body(entry)
    if entry.get("custom_case"):
        if "{{PROJECT_OVERVIEW}}" in content:
            keywords = json.loads((ROOT / "_data/keyword-research.json").read_text(encoding="utf-8"))["keywords"]
            strategy = json.loads((ROOT / "_data/content-strategy.json").read_text(encoding="utf-8"))
            deliverables = definition([
                ("Recovered keywords", str(len({row["term"] for row in keywords}))),
                ("Proposed audience personas", str(len(strategy["personas"]))),
                ("Content pillars", str(len(strategy["pillars"]))),
                ("Days of content planning", str(len({row["date"] for row in strategy["calendar"]}))),
            ], "kw-metrics")
            overview = (ROOT / "_content/cases/project-overview.html").read_text(encoding="utf-8")
            overview = overview.replace("{{TIMEFRAME}}", escape(entry["timeframe"])).replace("{{DELIVERABLES}}", deliverables)
            content = content.replace("{{PROJECT_OVERVIEW}}", overview)
        if "{{KEYWORD_STRATEGY}}" in content:
            content = content.replace("{{KEYWORD_STRATEGY}}", render_keyword_strategy(ROOT))
        if "{{CONTENT_STRATEGY}}" in content:
            for marker, section in render_content_strategy(ROOT).items():
                content = content.replace("{{" + marker + "}}", section)
        for marker, template in (
            ("CREATIVE_SHOWCASE", "creative-showcase"),
            ("STOREFRONT_EVIDENCE", "storefront-evidence"),
            ("NEWSLETTER_EVIDENCE", "newsletter-evidence"),
        ):
            if "{{" + marker + "}}" not in content:
                continue
            fragment = (ROOT / f"_content/cases/{template}.html").read_text(encoding="utf-8")
            if "{{POETRY_METRICS}}" in fragment:
                terms = json.loads((ROOT / "_data/keyword-research.json").read_text(encoding="utf-8"))["keywords"]
                poetry = next(row for row in terms if row["term"] == "poetry gifts")
                metrics = f'{poetry["volume"]:,} monthly searches and {poetry["difficulty"]:.0%} keyword difficulty'
                fragment = fragment.replace("{{POETRY_METRICS}}", metrics)
            content = content.replace("{{" + marker + "}}", fragment)
        return content
    skills = "".join(f'<li>{escape(skill)}</li>' for skill in entry["skills"])
    links = "".join(f'<li><a href="{external_url(link["url"])}">{escape(link["label"])}</a></li>'
                    for link in entry.get("external_links", []))
    return (
        '<p class="m"><a href="#work">Back to work</a></p>\n'
        f'<article><header class="pg"><h2 class="view-title" data-view-heading="1" tabindex="-1">{escape(entry["title"])}</h2>'
        f'<p class="m">{escape(entry["category"] + ", " + entry["timeframe"])}</p>'
        f'<p class="lead">{escape(entry["description"])}</p>{image_html(entry["image"])}</header>\n'
        f'{content}\n<section><h3 data-view-heading="2">Skills demonstrated</h3><ul>{skills}</ul></section>'
        + (f'<section><h3 data-view-heading="2">Related links</h3><ul>{links}</ul></section>' if links else "")
        + '</article>'
    )


def view(entry, content):
    title = escape(entry.get("case_title", entry["title"]))
    return f'    <div class="view" id="{anchor(entry, "work")}" data-section="work" data-page-title="{title}">\n{content}\n    </div>'


def legacy_view(entry, content, kind):
    old_anchor = anchor(entry, kind)
    destination = route(entry, kind)
    title = escape(entry["title"])
    section_links = "".join(
        f'<p id="{section}" data-forward="{destination}#{section}" tabindex="-1"><a href="{destination}#{section}">Continue to {escape(section)}</a></p>'
        for section in re.findall(r'<h[2-6]\b[^>]*\bid="([a-z0-9-]+)"', content)
    )
    return (
        f'<div class="view" id="{old_anchor}" data-section="{kind}" data-page-title="{title}" data-forward="{destination}">'
        f'<section class="pg"><h2 class="view-title" data-view-heading="1" tabindex="-1">{title}</h2>'
        f'<p><a href="{destination}">Continue to {title}</a></p>{section_links}</section></div>'
    )


def dedicated_page(entry, content, kind, template):
    url = SITE + route(entry, kind)
    seo = entry["seo"]
    title, description = escape(seo["title"]), escape(seo["description"])
    photo = seo.get("image") or entry.get("image", {}).get("src")
    if not photo:
        raise ValueError(f"{entry['id']}: add a social image before enabling a dedicated page")
    if not photo.startswith("assets/"):
        raise ValueError("Social image paths must start with assets/")
    local_file(photo, ".")
    head = template.split("</head>", 1)[0]
    head = re.sub(r'<title>.*?</title>', f'<title>{title}</title>', head)
    metadata = {
        "description": description, "og:title": title, "og:description": description,
        "twitter:card": "summary_large_image", "twitter:title": title, "twitter:description": description,
    }
    for name, value in metadata.items():
        head = re.sub(rf'((?:name|property)="{name}" content=")[^"]*"', lambda m: m[1] + value + '"', head)
    head = re.sub(r'<script src="assets/portfolio.js" defer></script>\n', "", head)
    head += (
        f'<link rel="canonical" href="{url}">\n<meta property="og:url" content="{url}">\n'
        f'<meta property="og:image" content="{escape(SITE + photo)}">\n'
        f'<meta name="twitter:image" content="{escape(SITE + photo)}">\n'
    )
    header = re.search(r'<header class="mh">.*?</header>', template, re.S)[0]
    footer = re.search(r'<footer class="m">.*?</footer>', template, re.S)[0]
    if kind == "writing":
        heading = f'<header class="pg"><h1 class="view-title">{escape(entry["title"])}</h1><p class="lead">{description}</p></header>'
        detail = body(entry) if entry.get("body") else f'<p><a href="{external_url(entry["external_url"])}">Read the original publication</a></p>'
        content = f'<article>{heading}{detail}<p><a href="#writing">Back to Writing</a></p></article>'
        # Article fragments use H4/H5 for the homepage feature. Raise them here.
        content = re.sub(r'<(/?)h([45])\b', lambda m: f'<{m[1]}h{int(m[2])-2}', content)
    else:
        # Shift project headings up from the index fallback hierarchy.
        content = re.sub(r'<(/?)h([2-6])\b', lambda m: f'<{m[1]}h{int(m[2])-1}', content)
        content = re.sub(r' data-view-heading="[1-5]"', "", content)
    content = re.sub(r'href="#(home|work|writing|about|contact)"', r'href="../../#\1"', content)
    for part in ("href", "src"):
        head = head.replace(f'{part}="assets/', f'{part}="../../assets/')
        content = content.replace(f'{part}="assets/', f'{part}="../../assets/')
    content = re.sub(r'srcset="([^"]+)"', lambda m: 'srcset="' + m[1].replace("assets/", "../../assets/") + '"', content)
    navigation = (header + footer).replace('href="#', 'href="../../#')
    header, footer = navigation.split("</header>", 1)
    return (
        f'{head}</head>\n<body>\n<a class="skip" href="#app">Skip to Main Content</a>\n'
        f'<div class="w">{header}</header><main id="app" tabindex="-1">{content}</main>{footer}</div>\n</body>\n</html>\n'
    )


def render():
    data = json.loads((ROOT / "_data/portfolio.json").read_text(encoding="utf-8"))
    template = (ROOT / "_content/index.template.html").read_text(encoding="utf-8")
    projects = list(published_entries(data["projects"], "work"))
    writing = list(published_entries(data["writing"], "writing"))
    cases, writing_redirects, pages = [], [], {}
    for kind, entries in (("work", projects), ("writing", writing)):
        for entry in entries:
            content = project_case(entry) if kind == "work" else ""
            if entry.get("dedicated"):
                pages[route(entry, kind) + "index.html"] = dedicated_page(entry, content, kind, template)
                redirect = legacy_view(entry, content, kind)
                (cases if kind == "work" else writing_redirects).append(redirect)
            elif kind == "work":
                cases.append(view(entry, content))
    replacements = {
        "HOME_PROJECTS": "\n".join(project_row(entry, i, True) for i, entry in enumerate(projects, 1)),
        "WORK_PROJECTS": "\n".join(project_row(entry, i, False) for i, entry in enumerate(projects, 1)),
        "CASE_VIEWS": "\n".join(cases),
        "WRITING": "\n".join(writing_feature(entry) for entry in writing),
        "WRITING_REDIRECTS": "\n".join(writing_redirects),
    }
    for key, value in replacements.items():
        template = template.replace("{{" + key + "}}", value)
    pages["index.html"] = template
    for path, page in pages.items():
        ids = re.findall(r'<[a-z][\w-]*\b[^>]*\sid="([^"]+)"', page)
        if len(ids) != len(set(ids)):
            raise ValueError(f"{path}: HTML anchor IDs must be unique")
    sitemap = Element("urlset", xmlns="http://www.sitemaps.org/schemas/sitemap/0.9")
    for path in sorted(pages):
        SubElement(SubElement(sitemap, "url"), "loc").text = SITE + path.removesuffix("index.html")
    pages = {path: page.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + MARKER, 1) for path, page in pages.items()}
    pages["sitemap.xml"] = '<?xml version="1.0" encoding="UTF-8"?>\n' + tostring(sitemap, encoding="unicode") + "\n"
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the generated files are up to date")
    args = parser.parse_args()
    pages = render()
    stale = [
        path for folder in ("work", "writing") for path in (ROOT / folder).glob("*/index.html")
        if path.relative_to(ROOT).as_posix() not in pages and MARKER in path.read_text(encoding="utf-8")
    ]
    if args.check:
        changed = [name for name, page in pages.items() if not (ROOT / name).exists() or (ROOT / name).read_text(encoding="utf-8") != page]
        if changed or stale:
            parser.error("Generate the portfolio again. Out of date: " + ", ".join(changed + [str(p.relative_to(ROOT)) for p in stale]))
    else:
        for name, page in pages.items():
            path = ROOT / name
            if name not in ("index.html", "sitemap.xml") and path.exists() and MARKER not in path.read_text(encoding="utf-8"):
                parser.error(f"Refusing to overwrite a hand-written page: {name}")
        for name, page in pages.items():
            path = ROOT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(page, encoding="utf-8")
        for path in stale:
            path.unlink()
    print(f"{len(pages)} publishing files {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
